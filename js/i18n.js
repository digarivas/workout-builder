  function t(key, ...args) {
    let text = (I18N[current] && I18N[current][key]) || (I18N.es[key] !== undefined ? I18N.es[key] : key);
    if (typeof text === "string") {
      args.forEach((a, i) => {
        text = text.replace("%" + (i + 1), String(a));
      });
    }
    return text;
  }

